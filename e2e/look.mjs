// Takes screenshots of the main screens for design review. Not a test.
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { startServer } from './server.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = decodeURIComponent(new URL('./out/look/', import.meta.url).pathname);
mkdirSync(out, { recursive: true });
const fxDir = decodeURIComponent(new URL('./out/fixtures/', import.meta.url).pathname);
const server = await startServer();
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 1.5, hasTouch: true, isMobile: true, serviceWorkers: 'block', colorScheme: process.argv[2] === 'dark' ? 'dark' : 'light' });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
const tag = process.argv[2] === 'dark' ? 'dark-' : '';
const shot = (n) => page.screenshot({ path: `${out}${tag}${n}.png` });
const go = async (hash) => { await page.evaluate((h) => { location.hash = h; }, hash); await page.waitForTimeout(700); };
await page.goto(server.url);
await page.waitForTimeout(800);
await shot('00-home-empty');
await go('#/library'); await shot('01-library-empty');
await go('#/references'); await shot('02-references-empty');
await go('#/');
await page.setInputFiles('[data-testid=add-input]', ['usul.epub', 'risala-text.pdf', 'makhtut-scan.pdf', 'urdu-risala.txt', '0204Shafici.Risala', 'Introduction to Usul - Vol 1.pdf', 'Introduction to Usul - Vol 2.pdf'].map((f) => fxDir + f));
await page.waitForTimeout(7000);
await go('#/library'); await shot('03-library');
await page.getByRole('button', { name: 'Open مختصر في أصول الفقه', exact: true }).click();
await page.waitForSelector('.bk'); await page.waitForTimeout(700);
await page.evaluate(() => {
  const p = document.querySelectorAll('.bk[data-t="p"]')[2];
  const r = document.createRange(); r.selectNodeContents(p);
  getSelection().removeAllRanges(); getSelection().addRange(r);
});
await page.waitForTimeout(400);
await page.getByRole('button', { name: 'Reference', exact: true }).click();
await page.waitForTimeout(5200);
await page.locator('.rd-scroll').evaluate((el) => el.scrollBy(0, 900));
await page.waitForTimeout(1200);
await shot('04-reader');
if ((await page.locator('.rd').getAttribute('data-chrome')) !== 'true') { await page.locator('.rd-scroll').click({ position: { x: 206, y: 500 } }); await page.waitForTimeout(400); }
await page.getByRole('button', { name: 'Contents, bookmarks and highlights' }).click();
await page.waitForTimeout(500); await shot('05-contents');
await page.goBack(); await page.waitForTimeout(400);
await page.goBack(); await page.waitForTimeout(700);
await go('#/'); await shot('06-home');
await page.evaluate(() => window.scrollTo(0, 500)); await page.waitForTimeout(300); await shot('07-home-lower');
await go('#/references'); await shot('08-references');
await go('#/library');
await page.getByRole('button', { name: 'Details for الرسالة' }).click();
await page.waitForTimeout(600); await shot('09-details');
await page.goBack(); await page.waitForTimeout(400);
await page.getByRole('button', { name: 'Open risala-text', exact: true }).click();
await page.waitForSelector('.bk'); await page.waitForTimeout(800); await shot('10-reader-pdf');
await go('#/settings'); await shot('11-settings');
await go('#/search'); await page.getByRole('searchbox').fill('القياس'); await page.waitForTimeout(2500); await shot('12-search');
await browser.close();
server.stop();
